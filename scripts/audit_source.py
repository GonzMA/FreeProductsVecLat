"""Check proof placeholders and generate library imports, inventory, and axiom audit.

Uses only Python's standard library. Source counts are not a transitive proof audit;
the generated scripts/ProofAudit.lean separately checks the registered declarations.
"""

import argparse
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parent.parent
BEGIN = "<!-- BEGIN SOURCE INVENTORY -->"
END = "<!-- END SOURCE INVENTORY -->"


def code_only(source):
    """Mask nested comments and strings while preserving offsets and line breaks."""
    result = list(source)
    i, depth, quoted = 0, 0, False
    while i < len(source):
        width = 1
        if depth:
            if source.startswith("/-", i):
                depth += 1
                width = 2
            elif source.startswith("-/", i):
                depth -= 1
                width = 2
        elif quoted:
            if source[i] == "\\":
                width = min(2, len(source) - i)
            elif source[i] == '"':
                quoted = False
        elif source.startswith("/-", i):
            depth, width = 1, 2
        elif source.startswith("--", i):
            end = source.find("\n", i)
            width = (len(source) if end < 0 else end) - i
        elif source[i] == '"':
            quoted = True
        else:
            i += 1
            continue
        for j in range(i, i + width):
            if source[j] != "\n":
                result[j] = " "
        i += width
    if depth or quoted:
        raise ValueError("Unterminated comment or string")
    return "".join(result)


def inventory(path):
    code = code_only(path.read_text())
    banned = re.search(r"\b(?:axiom|constant|admit|native_decide|sorryAx|unsafe)\b", code)
    if banned:
        raise ValueError(f"{path.name}: unexpected {banned.group()} token")
    pattern = re.compile(
        r"^(?:@\[[^\]]*\]\s*)*(?P<mod>(?:(?:private|protected|noncomputable)\s+)*)"
        r"(?P<kind>def|abbrev|theorem|lemma|structure|class|instance)\b"
        r"\s*(?P<name>[^\s(:={]+)?"
    )
    scopes, rows, offset = [], [], 0
    for line_number, line in enumerate(code.splitlines(keepends=True), 1):
        scope = re.match(r"^(namespace|section)\b\s*(\S*)", line)
        if scope:
            scopes.append((scope[1], scope[2]))
        elif re.match(r"^end\b", line) and scopes:
            scopes.pop()
        match = pattern.match(line)
        if match:
            name = match["name"] or f"<anonymous instance at {line_number}>"
            prefix = ".".join(name for kind, name in scopes if kind == "namespace")
            rows.append({
                "name": f"{prefix}.{name}" if prefix else name,
                "kind": match["kind"], "line": line_number, "offset": offset,
                "private": "private" in match["mod"],
            })
        offset += len(line)
    for index, row in enumerate(rows):
        end = rows[index + 1]["offset"] if index + 1 < len(rows) else len(code)
        row["gaps"] = len(re.findall(r"\bsorry\b", code[row["offset"]:end]))
    gaps = len(re.findall(r"\bsorry\b", code))
    if sum(row["gaps"] for row in rows) != gaps:
        raise ValueError(f"{path.name}: a placeholder is outside the parsed declarations")
    return rows


def lean_imports(files):
    lines = ["/-", "Authors: Gonzalo Martínez-Fernández", "-/", ""]
    for path in files:
        module = ".".join(path.relative_to(ROOT).with_suffix("").parts)
        lines.append(f"import {module}")
    lines += ["", "/-!", "# Free products of vector and Banach lattices", "",
              "Generated by scripts/audit_source.py. Imports all mathematical modules.",
              "The separate axiom audit is in scripts/ProofAudit.lean.", "-/"]
    return "\n".join(lines) + "\n"


def lean_audit(targets):
    lines = ["/-", "Authors: Gonzalo Martínez-Fernández", "-/", "",
              "import FreeProducts", "import Lean.Util.CollectAxioms", "", "/-!",
              "# Registered proof dependency checks", "",
              "Generated by scripts/audit_source.py from scripts/audit_targets.json.",
              "Run after lake build with: lake env lean scripts/ProofAudit.lean", "",
              "The strict registry admits only Lean's standard axioms. Tracked results",
              "report their dependencies and may still depend on unfinished proofs.",
              "-/", "", "open Lean Elab Command", "", "run_cmd do"]
    for group in ("verified", "tracked"):
        entries = ",\n".join("    ``" + name for name in targets[group])
        if entries:
            lines += [f"  let {group} : Array Name := #[", entries + "]"]
        else:
            lines.append(f"  let {group} : Array Name := #[]")
    lines += [
        "  let allowed : Array Name := #[``propext, ``Classical.choice, ``Quot.sound]",
        "  for name in verified do",
        "    let axioms ← collectAxioms name",
        "    for axiomName in axioms do",
        "      unless allowed.contains axiomName do",
        '        throwError m!"{name} depends on disallowed axiom {axiomName}"',
        '  logInfo m!"Strict axiom audit passed for {verified.size} registered declarations."',
        "  for name in tracked do",
        "    let axioms ← collectAxioms name",
        "    for axiomName in axioms do",
        "      unless allowed.contains axiomName || axiomName == ``sorryAx do",
        '        throwError m!"{name} depends on unexpected axiom {axiomName}"',
        '    logInfo m!"Tracked dependency audit: {name}: {axioms}"',
    ]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if generated files are stale")
    args = parser.parse_args()
    files = sorted((ROOT / "FreeProducts").rglob("*.lean"))
    data = [(p, inventory(p)) for p in files]
    targets = json.loads((ROOT / "scripts/audit_targets.json").read_text())
    source = {d["name"]: d for _, rows in data for d in rows if not d["private"]}
    for group, names in targets.items():
        for name in names:
            if name not in source:
                raise ValueError(f"Unknown public audit target: {name}")
            if group == "verified" and source[name]["gaps"]:
                raise ValueError(f"Strict audit target has an explicit gap: {name}")
    gaps = sum(d["gaps"] for _, rows in data for d in rows)
    lines = [BEGIN, "## Source inventory", "",
             f"**{gaps} explicit proof placeholders** across {len(files)} mathematical modules.",
             "Comments and strings are excluded. A gap-free source body does not certify its",
             "dependencies; only registered strict targets are checked transitively by Lean.", "",
             "| Module | Declarations | Explicit placeholders |", "|---|---:|---:|"]
    for path, rows in data:
        module = path.relative_to(ROOT / "FreeProducts").with_suffix("")
        lines.append(f"| [{module}]({path.relative_to(ROOT)}) | {len(rows)} | "
                     f"{sum(d['gaps'] for d in rows)} |")
    lines += ["", "### Open source declarations", "",
              "| Declaration | File | Placeholders |", "|---|---|---:|"]
    for path, rows in data:
        for row in rows:
            if row["gaps"]:
                link = f"{path.relative_to(ROOT)}#L{row['line']}"
                lines.append(f"| `{row['name']}` | [{path.name}:{row['line']}]({link}) | "
                             f"{row['gaps']} |")
    lines += ["", END]
    report = ROOT / "FORMALIZATION.md"
    before, rest = report.read_text().split(BEGIN, 1)
    _, after = rest.split(END, 1)
    outputs = {
        report: before + "\n".join(lines) + after,
        ROOT / "FreeProducts.lean": lean_imports(files),
        ROOT / "scripts/ProofAudit.lean": lean_audit(targets),
    }
    stale = []
    for path, content in outputs.items():
        if not path.exists() or path.read_text() != content:
            stale.append(str(path.relative_to(ROOT)))
            if not args.check:
                path.write_text(content)
    if args.check and stale:
        print("Regenerate with python3 scripts/audit_source.py: " + ", ".join(stale), file=sys.stderr)
        return 1
    print(f"{len(files)} modules; {gaps} explicit placeholders; "
          f"{len(targets['verified'])} strict audit targets; {len(targets['tracked'])} tracked targets.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
